"""Publication figure style for the thesis supplement.

One place for every colour and rcParam the figure scripts use, so the whole
supplement reads as a single system.

Colour rules followed here (all machine-validated, see module docstring notes):

* **Score (-1..5) is ordinal magnitude**, so it takes a single-hue blue ramp,
  light -> dark, never a rainbow and never eight categorical hues.  The 6- and
  7-step ramps below were generated by OKLab interpolation between the blue
  ramp's step-250 and step-700 anchors and pass the ordinal gate (monotone
  lightness, adjacent OKLCH dL >= 0.06, light end >= 2:1 against the surface,
  single hue).
* **Nominal groups** (feature family, epoch, feature set) take fixed
  categorical slots in a fixed order - blue, orange, aqua.  Those three pass
  the all-pairs CVD and normal-vision floors in light mode.
* **Magnitude heatmaps** use the one-hue blue sequential ramp; **signed
  quantities** (log ratios, correlations, differences) use a blue<->red
  diverging ramp with a neutral grey midpoint, so zero reads as "nothing".
"""

from __future__ import annotations

import matplotlib as mpl
import numpy as np
from matplotlib.colors import LinearSegmentedColormap

# --- chrome & ink ----------------------------------------------------------
SURFACE = "#fcfcfb"
PRIMARY = "#0b0b0b"
SECONDARY = "#52514e"
MUTED = "#898781"
GRID = "#e1e0d9"
AXIS = "#c3c2b7"

# --- ordinal score ramps (one hue, light -> dark) --------------------------
SCORE_RAMP_6 = ["#86b6ef", "#6d9bd3", "#5480b8", "#3c679e", "#254e84", "#0d366b"]
SCORE_RAMP_7 = ["#86b6ef", "#719fd8", "#5c89c1", "#4874ab", "#345f95", "#214a80", "#0d366b"]

# --- categorical slots (fixed order, never cycled) -------------------------
CAT = ["#2a78d6", "#eb6834", "#1baf7a"]

# --- sequential / diverging ramps ------------------------------------------
_SEQ_STEPS = ["#cde2fb", "#9ec5f4", "#5598e7", "#2a78d6", "#1c5cab", "#104281", "#0d366b"]
SEQ_CMAP = LinearSegmentedColormap.from_list("blue_seq", _SEQ_STEPS)
DIV_CMAP = LinearSegmentedColormap.from_list(
    "blue_red_div", ["#0d366b", "#2a78d6", "#86b6ef", "#f0efec", "#f0a09f", "#e34948", "#8f2323"]
)

# --- odor-window annotation -------------------------------------------------
ODOR_SHADE = "#f0efec"


def score_colors(levels) -> dict:
    """Map an ordered list of score levels onto the matching ordinal ramp."""
    levels = list(levels)
    ramp = SCORE_RAMP_6 if len(levels) <= 6 else SCORE_RAMP_7
    if len(levels) != len(ramp):
        idx = np.linspace(0, len(ramp) - 1, len(levels)).round().astype(int)
        ramp = [ramp[i] for i in idx]
    return dict(zip(levels, ramp))


