def tidy(ax, *, grid_axis: str = "y") -> None:
    """Recessive chrome: hairline grid on one axis only, no top/right spines."""
    ax.grid(False)
    if grid_axis in ("x", "both"):
        ax.xaxis.grid(True, color=GRID, linewidth=0.5)
    if grid_axis in ("y", "both"):
        ax.yaxis.grid(True, color=GRID, linewidth=0.5)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(AXIS)
        ax.spines[side].set_linewidth(0.6)


def mark_odor_window(ax, on_s: float, off_s: float, *, label: bool = False) -> None:
    """Shade the odor-on window; a solid hairline pair, never dashes."""
    ax.axvspan(on_s, off_s, color=ODOR_SHADE, zorder=0, linewidth=0)
    for x in (on_s, off_s):
        ax.axvline(x, color=AXIS, linewidth=0.6, zorder=1)
    if label:
        ax.text((on_s + off_s) / 2, 0.97, "odor on", transform=ax.get_xaxis_transform(),
                ha="center", va="top", fontsize=7, color=MUTED)


def ink_on(hex_color: str) -> str:
    """Ink that stays legible on top of ``hex_color`` — primary on light, surface on dark."""
    r, g, b = (int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5))
    lum = 0.2126 * r + 0.7152 * g + 0.0722 * b
    return PRIMARY if lum > 0.55 else SURFACE


def cell_grid(ax, n_rows: int, n_cols: int) -> None:
    """Hairline surface gaps between heatmap cells — a gap, never a border."""
    ax.set_xticks(np.arange(-0.5, n_cols, 1), minor=True)
    ax.set_yticks(np.arange(-0.5, n_rows, 1), minor=True)
    ax.grid(which="minor", color=SURFACE, linewidth=1.2)
    ax.tick_params(which="minor", length=0)


def colorbar(fig, im, ax, label: str, **kw):
    """A recessive colorbar: no outline, small label, tight to its axes."""
    cb = fig.colorbar(im, ax=ax, **{"fraction": 0.040, "pad": 0.02, **kw})
    cb.set_label(label, fontsize=7)
    cb.ax.tick_params(labelsize=6.5, length=2)
    cb.outline.set_visible(False)
    return cb


def save(fig, outdir, stem: str) -> None:
    """Write vector PDF (for the thesis) and 400 dpi PNG (for quick viewing)."""
    from pathlib import Path

    outdir = Path(outdir)
    (outdir / "pdf").mkdir(parents=True, exist_ok=True)
    (outdir / "png").mkdir(parents=True, exist_ok=True)
    fig.savefig(outdir / "pdf" / f"{stem}.pdf")
    fig.savefig(outdir / "png" / f"{stem}.png")
    print(f"  saved {stem}.pdf / .png")
